#!/usr/bin/env node
/**
 * Regenerates src/vehicleData/dtcDescriptions.ts from a CSV of generic DTC
 * codes/descriptions. There is no single official machine-readable export
 * of the SAE J2012 generic code list, so this script takes a local CSV you
 * provide (two columns: code,description) rather than fetching one — the
 * bundled table was hand-curated from the standard for the same reason.
 *
 * Usage:
 *   node scripts/generate-dtc-table.js path/to/dtc-codes.csv
 *
 * CSV format (no header row):
 *   P0100,Mass or Volume Air Flow Circuit Malfunction
 *   P0301,Cylinder 1 Misfire Detected
 *   ...
 */
const fs = require('fs');
const path = require('path');

const csvPath = process.argv[2];
if (!csvPath) {
  console.error('Usage: node scripts/generate-dtc-table.js <path-to-csv>');
  process.exit(1);
}

const outPath = path.join(__dirname, '..', 'src', 'vehicleData', 'dtcDescriptions.ts');

const lines = fs
  .readFileSync(csvPath, 'utf8')
  .split(/\r?\n/)
  .map((l) => l.trim())
  .filter(Boolean);

const entries = lines.map((line) => {
  const idx = line.indexOf(',');
  const code = line.slice(0, idx).trim().toUpperCase();
  const description = line
    .slice(idx + 1)
    .trim()
    .replace(/^"|"$/g, '')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'");
  if (!/^[PCBU][0-3][0-9A-F]{3}$/.test(code)) {
    throw new Error(`Invalid DTC code format: "${code}"`);
  }
  return { code, description };
});

entries.sort((a, b) => a.code.localeCompare(b.code));

const body = entries.map((e) => `  ${e.code}: '${e.description}',`).join('\n');

const output = `/**
 * Bundled subset of SAE J2012 / ISO 15031-6 generic (P0xxx/C0xxx/B0xxx/U0xxx)
 * DTC descriptions. Generic codes are standardized across all OBD2 vehicles;
 * manufacturer-specific codes (P1xxx etc.) are not decoded offline.
 *
 * Generated by scripts/generate-dtc-table.js — see docs/VEHICLE_DATA.md.
 * Do not hand-edit; re-run the generator against an updated CSV instead.
 */
export const DTC_DESCRIPTIONS: Record<string, string> = {
${body}
};

export function describeDtc(code: string): string {
  return DTC_DESCRIPTIONS[code] ?? 'Unknown / manufacturer-specific code';
}
`;

fs.writeFileSync(outPath, output);
console.log(`Wrote ${entries.length} DTC entries to ${path.relative(process.cwd(), outPath)}`);
